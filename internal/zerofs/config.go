package zerofs

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"strconv"
	"strings"
)

// Storage is the S3-compatible bucket ZeroFS persists to.
type Storage struct {
	// URL is the bucket and prefix, such as "s3://my-bucket/keepsync".
	URL string
	// Endpoint is the S3 API endpoint for non-AWS services (R2, MinIO, ...).
	// Empty means AWS.
	Endpoint        string
	Region          string
	AccessKeyID     string
	SecretAccessKey string
	// AllowHTTP permits a plain-http Endpoint (local MinIO in tests).
	AllowHTTP bool
}

// PasswordBytes is the amount of randomness in a generated password.
const PasswordBytes = 32

// GeneratePassword returns a new ZeroFS encryption password: 32 random bytes,
// hex encoded. Hex keeps it free of characters ZeroFS's config expansion or a
// shell would treat specially.
func GeneratePassword() (string, error) {
	b := make([]byte, PasswordBytes)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

// ImportPassword reads an existing ZeroFS password from a file, for adopting a
// bucket that already has data (server init --zerofs-password-file). One
// trailing newline is stripped; anything else is taken verbatim.
func ImportPassword(path string) (string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	pw := strings.TrimSuffix(strings.TrimSuffix(string(b), "\n"), "\r")
	if err := ValidatePassword(pw); err != nil {
		return "", fmt.Errorf("%s: %w", path, err)
	}
	return pw, nil
}

// ValidatePassword applies ZeroFS's own rules, so a bad password fails here
// instead of at zerofs startup.
func ValidatePassword(pw string) error {
	switch {
	case pw == "":
		return errors.New("zerofs: empty password")
	case len(pw) < 8:
		return errors.New("zerofs: password shorter than 8 bytes")
	case pw == "CHANGEME":
		return errors.New("zerofs: password is the ZeroFS default")
	}
	return nil
}

// Environment variables the generated config refers to. Secrets are passed to
// zerofs through its environment, so zerofs.toml holds none of them.
const (
	envPassword  = "KEEPSYNC_ZEROFS_PASSWORD"
	envAccessKey = "KEEPSYNC_ZEROFS_ACCESS_KEY_ID"
	envSecretKey = "KEEPSYNC_ZEROFS_SECRET_ACCESS_KEY"
)

// configParams is everything RenderConfig needs.
type configParams struct {
	Storage     Storage
	CacheDir    string
	CacheSizeGB float64
	MemoryGB    float64
	NinePSocket string
	RPCSocket   string
}

// renderConfig produces zerofs.toml. Only the 9P and RPC servers are enabled,
// both on unix sockets: no NFS (it reports writes stable while they are still
// buffered), no NBD, no web UI, and telemetry off.
func renderConfig(p configParams) string {
	var b strings.Builder
	q := strconv.Quote
	f := func(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }
	fmt.Fprintf(&b, "# Generated by keepsync for ZeroFS %s. Do not edit; keepsync rewrites it on start.\n", PinnedVersion)
	fmt.Fprintf(&b, "# Secrets come from the environment keepsync starts zerofs with.\n\n")
	fmt.Fprintf(&b, "[cache]\ndir = %s\ndisk_size_gb = %s\nmemory_size_gb = %s\n\n", q(p.CacheDir), f(p.CacheSizeGB), f(p.MemoryGB))
	fmt.Fprintf(&b, "[storage]\nurl = %s\nencryption_password = \"${%s}\"\n\n", q(p.Storage.URL), envPassword)
	fmt.Fprintf(&b, "[servers.ninep]\nunix_socket = %s\n\n", q(p.NinePSocket))
	fmt.Fprintf(&b, "[servers.rpc]\nunix_socket = %s\n\n", q(p.RPCSocket))
	fmt.Fprintf(&b, "[telemetry]\nenabled = false\n")
	if strings.HasPrefix(p.Storage.URL, "s3://") {
		fmt.Fprintf(&b, "\n[aws]\n")
		if p.Storage.AccessKeyID != "" || p.Storage.SecretAccessKey != "" {
			fmt.Fprintf(&b, "access_key_id = \"${%s}\"\nsecret_access_key = \"${%s}\"\n", envAccessKey, envSecretKey)
		}
		if p.Storage.Endpoint != "" {
			fmt.Fprintf(&b, "endpoint = %s\n", q(p.Storage.Endpoint))
		}
		if p.Storage.Region != "" {
			fmt.Fprintf(&b, "default_region = %s\n", q(p.Storage.Region))
		}
		if p.Storage.AllowHTTP {
			fmt.Fprintf(&b, "allow_http = \"true\"\n")
		}
	}
	return b.String()
}
